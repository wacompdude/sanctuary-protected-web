/** Union permission keys from one or more church roles (deduped). */
export function unionRolePermissions(roles: string[]): PermissionKey[] {
  const set = new Set<PermissionKey>();
  for (const role of roles) {
    const perms = ROLE_PERMISSION_MAPPING[role] ?? [];
    for (const key of perms) set.add(key);
  }
  return [...set];
}
